// R2Config carries the Cloudflare R2 settings (.env.example: R2_*).
type R2Config struct {
	Endpoint        string // R2_ENDPOINT
	AccessKeyID     string // R2_ACCESS_KEY_ID
	SecretAccessKey string // R2_SECRET_ACCESS_KEY
	BucketPrivate   string // R2_BUCKET_PRIVATE
}

// R2 will implement Store against Cloudflare R2 (S3 API) with presigned
// URLs. TODO(phase-2): implement with AWS SigV4 presigning; until then NewR2
// fails fast when production storage is requested, and deployments keep
// using the local adapter only outside production.
type R2 struct {
	cfg R2Config
}

// NewR2 validates the config and returns the adapter.
func NewR2(cfg R2Config) (*R2, error) {
	if cfg.Endpoint == "" || cfg.AccessKeyID == "" || cfg.SecretAccessKey == "" || cfg.BucketPrivate == "" {
		return nil, errors.New("storage: R2_ENDPOINT, R2_ACCESS_KEY_ID, R2_SECRET_ACCESS_KEY and R2_BUCKET_PRIVATE are required")
	}
	return &R2{cfg: cfg}, nil
}

